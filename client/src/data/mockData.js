/**
 * Calculates consistent inventory statistics derived strictly from a medicines array.
 */
export function calculateInventoryMetrics(medicinesList = INITIAL_MEDICINES) {
  const total = medicinesList.length;
  let inStock = 0;
  let lowStock = 0;
  let outOfStock = 0;
  let totalValue = 0;

  const lowStockItems = [];

  medicinesList.forEach((item) => {
    const stock = Number(item.currentStock) || 0;
    const reorder = Number(item.reorderLevel) || 0;
    const cost = Number(item.purchasePrice) || 0;

    totalValue += stock * cost;

    if (stock === 0) {
      outOfStock += 1;
      lowStockItems.push({
        id: item.id,
        medicine: item.name,
        sku: item.sku,
        category: item.category,
        currentStock: stock,
        reorderLevel: reorder,
        unit: item.unit || 'units',
        severity: 'critical',
      });
    } else if (stock <= reorder) {
      lowStock += 1;
      lowStockItems.push({
        id: item.id,
        medicine: item.name,
        sku: item.sku,
        category: item.category,
        currentStock: stock,
        reorderLevel: reorder,
        unit: item.unit || 'units',
        severity: stock <= reorder * 0.3 ? 'critical' : 'warning',
      });
    } else {
      inStock += 1;
    }
  });

  // Sort low-stock alerts with critical items first
  lowStockItems.sort((a, b) => {
    if (a.severity === 'critical' && b.severity !== 'critical') return -1;
    if (a.severity !== 'critical' && b.severity === 'critical') return 1;
    return a.currentStock - b.currentStock;
  });

  return {
    totalMedicines: total,
    inStockCount: inStock,
    lowStockCount: lowStock,
    outOfStockCount: outOfStock,
    totalAlertsCount: lowStock + outOfStock,
    totalInventoryValue: totalValue,
    lowStockItems,
  };
}

