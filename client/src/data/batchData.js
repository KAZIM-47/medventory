/**
 * Calculates days remaining from simulated current date (Nov 04, 2026).
 */
export function getDaysUntilExpiry(expiryDateStr) {
  const simulatedNow = new Date('2026-11-04T00:00:00');
  const expDate = new Date(`${expiryDateStr}T00:00:00`);
  const diffTime = expDate - simulatedNow;
  return Math.ceil(diffTime / (1000 * 60 * 60 * 24));
}

/**
 * Returns 'Expired', 'Expiring Soon' (<=60 days), or 'Good'.
 */
export function getExpiryStatus(expiryDateStr) {
  const days = getDaysUntilExpiry(expiryDateStr);
  if (days < 0) return 'Expired';
  if (days <= 60) return 'Expiring Soon';
  return 'Good';
}

/**
 * Returns 'Out of Stock', 'Low Stock', or 'In Stock'.
 */
export function getBatchStockStatus(quantity, reorderLevel = 25) {
  const q = Number(quantity) || 0;
  if (q === 0) return 'Out of Stock';
  if (q <= reorderLevel * 0.35 || q <= 15) return 'Low Stock';
  return 'In Stock';
}

/**
 * Aggregates batch-level metrics for the Inventory Overview.
 */
export function calculateBatchInventoryMetrics(batchesList = INITIAL_BATCHES, medicinesList = INITIAL_MEDICINES) {
  let totalUnits = 0;
  let totalValue = 0;
  let lowStockBatches = 0;
  let expiringBatches = 0;

  batchesList.forEach((b) => {
    const q = Number(b.quantity) || 0;
    const cost = Number(b.purchasePrice) || 0;
    totalUnits += q;
    totalValue += q * cost;

    const stockStatus = getBatchStockStatus(q, b.reorderLevel);
    if (stockStatus === 'Low Stock') {
      lowStockBatches += 1;
    }

    const expStatus = getExpiryStatus(b.expiryDate);
    if (expStatus === 'Expiring Soon' || expStatus === 'Expired') {
      expiringBatches += 1;
    }
  });

  const outOfStockMeds = medicinesList.filter((m) => Number(m.currentStock) === 0).length;

  return {
    totalUnits,
    totalValue,
    lowStockBatches,
    expiringBatches,
    outOfStockMeds,
  };
}

